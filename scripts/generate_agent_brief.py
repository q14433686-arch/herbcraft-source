#!/usr/bin/env python3
"""Generate a compact current handoff brief for future AI/agent sessions.

The generated brief is intentionally derived from current workspace files so the
next assistant does not rely on stale chat memory. It does not replace source
inspection; it points the next agent to the authoritative files and current
release outputs.
"""

from __future__ import annotations

import argparse
import datetime as dt
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_OUT = ROOT / "docs" / "reports" / "CURRENT_AGENT_BRIEF.md"
RELEASE_DIR = ROOT / "release_output" / "herbcraft_test_20260614_review"


def read(path: str | Path) -> str:
    p = ROOT / path if isinstance(path, str) else path
    return p.read_text(encoding="utf-8") if p.exists() else ""


def first_lines(text: str, max_lines: int) -> str:
    lines = text.splitlines()
    return "\n".join(lines[:max_lines]).rstrip()


def section_from(text: str, marker: str, max_lines: int) -> str:
    idx = text.find(marker)
    if idx < 0:
        return ""
    return first_lines(text[idx:], max_lines)


def current_version() -> str:
    m = re.search(r"version\s*=\s*['\"]([^'\"]+)['\"]", read("build.gradle"))
    return m.group(1) if m else "UNKNOWN"


def release_files() -> str:
    if not RELEASE_DIR.exists():
        return "(release_output directory not found)"
    rows = []
    for p in sorted(RELEASE_DIR.iterdir()):
        if p.is_file():
            rows.append(f"- `{p.name}`")
    return "\n".join(rows) if rows else "(no files)"


def validation_block() -> str:
    baseline = read("CURRENT_BASELINE.md")
    marker = "## Current key validators"
    block = section_from(baseline, marker, 45)
    return block or "See `CURRENT_BASELINE.md` for the current validator list."


def build_brief() -> str:
    version = current_version()
    now = dt.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    baseline = read("CURRENT_BASELINE.md")
    next_task = read("NEXT_TASK.md")
    changelog = read("CHANGELOG.md")
    docs_index = read("docs/DOCUMENTATION_INDEX.md")

    baseline_current = section_from(baseline, "## Current baseline", 35)
    baseline_last = section_from(baseline, "## Last updated", 8)
    next_head = first_lines(next_task, 90)
    changelog_head = first_lines(changelog, 80)
    docs_head = first_lines(docs_index, 95)

    return f"""# Current Agent Brief

Generated: {now}  
Detected project version: `{version}`

This file is generated by:

```bash
python3 scripts/generate_agent_brief.py --write
```

Use this as the first compact handoff, then verify against source. Do not treat old chat memory as authoritative.

## 1. Mandatory priority order

```text
User's current request > current source/resources > current documentation > older reports/chat memory
```

If this brief conflicts with actual source, trust source and update the docs.

## 2. Non-negotiable architecture rules

- Java owns mechanics, registries, reload timing, sync, UI, validation, and events.
- JSON owns content, balance values, nutrition/nature data, guide/hint text tables, compatibility tables, and rules where loaders exist.
- Do not hardcode third-party compatibility tables in Java when JSON can express them.
- If an item is not edible in its source mod, do not put it in 食材录 / 药食志 unless a deliberate startup-only `herbs` component override is designed and documented.
- `data/<namespace>/herbcraft/herbs/*.json` is startup-only for FOOD/CONSUMABLE component changes; it is not world datapack `/reload` edible-component hot mutation.
- Reload-safe metadata paths include `herb_natures`, `nutrition_profiles`, `ingredients`, `special_counters`, `knowledge_rumors`, and `codex_loot_injections`.
- P4 read/event boundary is complete; Java write/registration APIs remain deferred.

## 3. Required first reads for future agents

Read in this order:

```text
CURRENT_BASELINE.md
docs/DOCUMENTATION_INDEX.md
NEXT_TASK.md
docs/JSON_EXTENSION_SPEC_1_1_4.md
docs/EXTENDING_HERBCRAFT.md
docs/PUBLIC_EXTENSION_API_DESIGN.md
docs/EXTERNAL_EXTENSION_SPEC_DRAFT.md
CHANGELOG.md
```

For generated/current handoff, regenerate this file before coding:

```bash
python3 scripts/generate_agent_brief.py --write
```

## 4. Current release output files

{release_files()}

## 5. Current baseline excerpt

```md
{baseline_current}
```

## 6. Last baseline update

```md
{baseline_last}
```

## 7. NEXT_TASK excerpt

```md
{next_head}
```

## 8. Latest CHANGELOG excerpt

```md
{changelog_head}
```

## 9. Documentation index excerpt

```md
{docs_head}
```

## 10. Validation commands reference

```md
{validation_block()}
```

## 11. End-of-turn requirements

If you change source, resources, docs, validators, versions, or release outputs:

1. Update `CURRENT_BASELINE.md`.
2. Update `NEXT_TASK.md` if the next action changed.
3. Update `CHANGELOG.md`.
4. Update relevant docs/specs/reports.
5. Refresh `release_output/herbcraft_test_20260614_review/herbcraft-source-current-20260614.zip`.
6. If jars changed, rebuild and refresh the jars in `release_output/herbcraft_test_20260614_review/`.
7. State exactly which validations were run.
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help=f"Write {DEFAULT_OUT.relative_to(ROOT)}")
    parser.add_argument("--output", type=Path, default=DEFAULT_OUT, help="Output markdown path")
    args = parser.parse_args()
    content = build_brief()
    if args.write:
        out = args.output
        if not out.is_absolute():
            out = ROOT / out
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(content, encoding="utf-8")
        print(f"Wrote {out.relative_to(ROOT)}")
    else:
        print(content)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
